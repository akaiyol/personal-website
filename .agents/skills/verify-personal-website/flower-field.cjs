const assert = require('assert');
async function checkFlowerField(page, expectedPlants) {
  const field = page.locator('#flower-field');
  await field.scrollIntoViewIfNeeded();
  await field.focus();
  await page.keyboard.press('End');
  await page.waitForFunction(count => Number(document.querySelector('#flower-art').dataset.plants) === count && document.querySelector('#flower-art').dataset.progress === '1.000000', expectedPlants);
  assert(await page.locator('.flower-growth-hint').isHidden(), 'Growth hint should disappear after interaction');
  const size = await page.locator('#flower-art').boundingBox();
  assert(size.width > 0 && size.height > 0, 'Flower canvas has no rendered area');
  await page.keyboard.press('ArrowLeft');
  await page.waitForFunction(() => Number(document.querySelector('#flower-art').dataset.progress) < 1);
  await page.keyboard.press('Home');
  await page.waitForFunction(() => document.querySelector('#flower-art').dataset.progress === '0.000000');
  const scrollBefore = await page.evaluate(() => scrollY);
  await page.keyboard.press('ArrowDown');
  await page.waitForFunction(() => document.querySelector('#flower-art').dataset.progress === '0.040000');
  await page.keyboard.press('ArrowUp');
  await page.waitForFunction(() => document.querySelector('#flower-art').dataset.progress === '0.000000');
  const box = await field.boundingBox();
  await page.mouse.move(box.x + box.width / 2, Math.max(100, Math.min(box.y + box.height / 2, page.viewportSize().height - 160)));
  await page.mouse.wheel(0, 280);
  await page.waitForFunction(() => document.querySelector('#flower-art').dataset.progress === '0.200000');
  await page.mouse.wheel(0, -140);
  await page.waitForFunction(() => document.querySelector('#flower-art').dataset.progress === '0.100000');
  await page.mouse.wheel(140, 0);
  await page.waitForFunction(() => document.querySelector('#flower-art').dataset.progress === '0.200000');
  await page.waitForTimeout(150);
  assert.equal(await page.evaluate(() => scrollY), scrollBefore, 'Growth inputs must not scroll the website');
  await page.keyboard.press('End');
  await page.waitForFunction(() => document.querySelector('#flower-art').dataset.progress === '1.000000');
  await page.mouse.wheel(0, 280);
  await page.waitForTimeout(150);
  assert.equal(await page.locator('#flower-art').getAttribute('data-progress'), '1.000000');
  assert.equal(await page.evaluate(() => scrollY), scrollBefore, 'Wheel at full growth must remain contained');
  await page.keyboard.press('Home');
  await page.waitForFunction(() => document.querySelector('#flower-art').dataset.progress === '0.000000');
  await page.mouse.wheel(0, -280);
  await page.waitForTimeout(150);
  assert.equal(await page.locator('#flower-art').getAttribute('data-progress'), '0.000000');
  assert.equal(await page.evaluate(() => scrollY), scrollBefore, 'Wheel at zero growth must remain contained');
  await page.mouse.move(10, 150);
  await page.mouse.wheel(0, -300);
  await page.waitForFunction(before => scrollY < before, scrollBefore);
  await field.scrollIntoViewIfNeeded();
  await field.focus();
  await page.keyboard.press('End');
  await page.waitForFunction(() => document.querySelector('#flower-art').dataset.progress === '1.000000');
}
module.exports = { checkFlowerField };
